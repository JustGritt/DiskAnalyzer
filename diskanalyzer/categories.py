"""Classification of space into human-meaningful buckets.

Knowing that your user folder holds 300 GB is not actionable. Knowing that
84 GB of it is regenerable build output and 40 GB is installers you already ran
is. Every rule here answers one question: if this space matters to you, what
would you do about it?

Confidence levels
-----------------
safe    Regenerable or already-discarded data. Cost of removal is time.
review  Very often unwanted, but only you know. Look before acting.
info    Not junk. Reported so the total adds up and you can see the shape.

DiskAnalyzer never removes anything itself; these labels exist to say where
looking is worthwhile.

Path patterns are written with forward slashes and matched against a
slash-normalized copy of the path. Windows accepts either separator, and this
keeps the rule table readable instead of a thicket of escaped separators.
"""

