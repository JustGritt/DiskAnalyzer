# --------------------------------------------------------------------------
# Extension rules, applied per file. The size floor keeps trivia out of the
# report: a 4 KB .log is noise, a 4 GB .log is a finding.
# --------------------------------------------------------------------------
MB = 1024 * 1024

EXT_RULES: dict[str, tuple[str, int]] = {}


def _register(names: str, category: str, min_size: int) -> None:
    for ext in names.split():
        EXT_RULES["." + ext] = (category, min_size)


_register("vhd vhdx vmdk vdi qcow2 ova ovf hdd avhdx", "vm-disk", 64 * MB)
_register("iso img cue nrg mdf dmg", "disc-image", 32 * MB)
_register("zip 7z rar tar gz tgz bz2 xz zst cab wim esd", "disc-image", 32 * MB)
_register("log etl dmp mdmp hdmp evtx trace", "logs", 8 * MB)
_register("ushaderprecache nvph shadercache", "app-cache", 8 * MB)
_register("bak old orig backup pst ost nsf", "backup", 8 * MB)
_register("mp4 mkv avi mov wmv flv webm m4v mpg mpeg vob", "media", 16 * MB)
_register("wav flac aiff ape m4a mp3 ogg", "media", 8 * MB)
_register("psd ai blend fbx max c4d cr2 nef arw dng tiff", "media", 8 * MB)

# Installers get their own callout when they turn up outside a package cache.
INSTALLER_EXTS = frozenset({".exe", ".msi", ".msix", ".appx", ".msu"})


def resolve_category(
    inherited: str | None, path_slash_lower: str, name_lower: str
) -> str | None:
    """Classify one directory, given whatever its parent was classified as.

    ``path_slash_lower`` must already be lowercased with forward slashes; the
    scanner does that once per directory instead of once per rule.

    Order matters, and it is chosen so the common case stays cheap. A folder
    named ``node_modules`` is that thing no matter what encloses it, and the
    check is one dict lookup, so names win outright. Overrides come next, for
    the few places a broad ancestor rule would otherwise hide something more
    specific. Only a directory with no inherited category pays for the full
    path-rule scan, which is what keeps this affordable across half a million
    folders.
    """
    hit = DIR_NAME_RULES.get(name_lower)
    if hit is not None:
        return hit
    for needle, key in OVERRIDE_PATH_RULES:
        if needle in path_slash_lower:
            return key
    if inherited is not None:
        return inherited
    for needle, key in DIR_PATH_RULES:
        if needle in path_slash_lower:
            return key
    return None


def match_directory(path_slash_lower: str, name_lower: str) -> str | None:
    """Classify a directory in isolation, ignoring anything above it."""
    return resolve_category(None, path_slash_lower, name_lower)


def match_extension(ext_lower: str, size: int) -> str | None:
    """Return a category key for a file by extension, or None."""
    rule = EXT_RULES.get(ext_lower)
    if rule is None:
        return None
    key, min_size = rule
    return key if size >= min_size else None
